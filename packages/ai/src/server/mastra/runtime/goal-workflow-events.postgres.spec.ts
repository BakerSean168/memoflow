import { randomUUID } from 'node:crypto';
import { PostgresStore } from '@mastra/pg';
import type { WorkflowRunState } from '@mastra/core/workflows';
import { describe, expect, it, vi } from 'vitest';
import { createMastraStorage } from './storage';
import { getGoalWorkflowEventSource } from './goal-workflow-events.registry';
import { publishRunningGoalActions } from '../workflows/goal-business-action-journal';

const connectionString = process.env.MEMOFLOW_GOAL_EVENTS_PG_URL;

describe.skipIf(!connectionString)('Goal committed event journal over real Postgres', () => {
  it('isolates identities, rolls back capture and replays a transaction that commits after a later event', async () => {
    if (!connectionString) throw new Error('Postgres event test requires a database URL');
    const schema = `mf_goal_events_test_${randomUUID().replaceAll('-', '').slice(0, 16)}`;
    const storage = createMastraStorage({ kind: 'postgres', connectionString, schemaName: schema });
    if (!(storage instanceof PostgresStore))
      throw new Error('Postgres test storage is unavailable');
    let transaction: Awaited<ReturnType<typeof storage.db.connect>> | undefined;
    try {
      await storage.init();
      const source = getGoalWorkflowEventSource(storage);
      if (!source) throw new Error('Goal event journal is unavailable');
      const workflows = await storage.getStore('workflows');
      if (!workflows) throw new Error('Workflow storage is unavailable');
      const snapshot = {
        status: 'running',
        context: { input: { idea: 'Plan', identityId: 'owner', conversationId: 'thread' } },
        value: { liveActions: [] },
      };
      const persist = (runId: string) =>
        workflows.persistWorkflowSnapshot({
          workflowName: 'goal-create',
          runId,
          resourceId: 'owner',
          snapshot: snapshot as unknown as WorkflowRunState,
        });
      const wake = vi.fn();
      const unsubscribe = source.subscribe(wake);
      await persist('preview');
      await vi.waitFor(() => expect(wake).toHaveBeenCalled());
      unsubscribe();
      const action = {
        sequence: 1,
        command: {
          actionId: 'name',
          revision: 1,
          operation: 'goal.setName' as const,
          value: 'Native Goal',
        },
      };
      await publishRunningGoalActions({
        storage,
        identityId: 'owner',
        runId: 'preview',
        journal: [action],
      });
      expect((await source.read('owner', 0)).at(-1)).toMatchObject({
        resourceVersion: 2,
        actions: [action],
      });
      expect(await source.read('foreign-owner', 0)).toEqual([]);
      transaction = await storage.db.connect();
      await transaction.query('BEGIN');
      await transaction.query(
        `UPDATE "${schema}".mastra_workflow_snapshot SET snapshot=jsonb_set(snapshot,'{status}','"canceled"') WHERE run_id='preview'`,
      );
      await transaction.query('ROLLBACK');
      expect(await source.snapshot('owner', 'preview')).toMatchObject({
        status: 'running',
        liveActions: [action],
      });
      await persist('late');
      const before = await source.head('owner');
      await transaction.query('BEGIN');
      await transaction.query(
        `UPDATE "${schema}".mastra_workflow_snapshot SET snapshot=jsonb_set(snapshot,'{status}','"canceled"') WHERE run_id='late'`,
      );
      await persist('early');
      const committed = await source.read('owner', before.last);
      expect(committed).toHaveLength(1);
      expect(committed[0]?.run.runId).toBe('early');
      await transaction.query('COMMIT');
      const late = await source.read('owner', committed[0]!.sequence);
      expect(late).toHaveLength(1);
      expect(late[0]?.run).toMatchObject({ runId: 'late', status: 'cancelled' });
      const second = createMastraStorage({
        kind: 'postgres',
        connectionString,
        schemaName: schema,
      });
      if (!(second instanceof PostgresStore))
        throw new Error('Postgres restart storage unavailable');
      try {
        await second.init();
        const restored = getGoalWorkflowEventSource(second)!;
        expect(restored.epoch).toBe(source.epoch);
        expect(await restored.read('owner', committed[0]!.sequence)).toHaveLength(1);
      } finally {
        await second.close();
      }
    } finally {
      if (transaction) {
        await transaction.query('ROLLBACK');
        transaction.release();
      }
      // The schema is generated by this test and never selects an application schema.
      if (!/^mf_goal_events_test_[a-f0-9]{16}$/.test(schema))
        throw new Error('Unsafe test cleanup schema');
      await storage.db.none(`DROP SCHEMA IF EXISTS "${schema}" CASCADE`);
      await storage.close();
    }
  }, 60_000);
});
